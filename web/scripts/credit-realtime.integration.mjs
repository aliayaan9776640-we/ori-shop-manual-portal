import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec(`create role anon; create role authenticated; create schema auth;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql as $$select current_setting('test.uid',true)::uuid$$;
create table customers(id uuid primary key,name text,phone text,balance numeric,credit_limit numeric,approval_status text);
create table public_customers(auth_user_id uuid,name text,phone text);
create publication supabase_realtime;
insert into auth.users values ('00000000-0000-0000-0000-000000000001'),('00000000-0000-0000-0000-000000000002');
insert into public_customers values ('00000000-0000-0000-0000-000000000001','Alice','123'),('00000000-0000-0000-0000-000000000002','Bob','456');`);
await db.exec(await readFile(new URL('../supabase/migrations/0044_credit_realtime.sql',import.meta.url),'utf8'));
await db.exec(`insert into customers values ('10000000-0000-0000-0000-000000000001','Alice','123',100,1000,'approved'),('10000000-0000-0000-0000-000000000002','Bob','456',200,2000,'approved');`);
await db.exec(`set test.uid='00000000-0000-0000-0000-000000000001'; set role authenticated;`);
let rows=(await db.query('select * from credit_refresh_signals')).rows;
assert.equal(rows.length,1,'Only own signal is visible');
assert.equal(rows[0].customer_id,'10000000-0000-0000-0000-000000000001');
assert.deepEqual(Object.keys(rows[0]).sort(),['auth_user_id','changed_at','customer_id'],'No credit details are published');
await assert.rejects(db.exec('delete from credit_refresh_signals'),/permission denied/);
await db.exec('reset role');
const before=rows[0].changed_at;
await db.exec(`update customers set balance=50 where name='Alice'`);
rows=(await db.query(`select * from credit_refresh_signals where auth_user_id='00000000-0000-0000-0000-000000000001'`)).rows;
assert.notEqual(rows[0].changed_at,before,'Payment refreshes signal');
assert.equal((await db.query(`select count(*)::int as n from credit_refresh_signals`)).rows[0].n,2,'Signals are upserted, not accumulated');
const published=(await db.query(`select tablename from pg_publication_tables where pubname='supabase_realtime'`)).rows;
assert.deepEqual(published.map(r=>r.tablename),['credit_refresh_signals'],'Sensitive tables are not published');
await db.close(); console.log('PASS: private credit signals, payment updates, RLS isolation, immutable client access, and no financial table publication.');
